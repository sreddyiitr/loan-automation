package com.funding.domain.build;

import com.funding.domain.RuleCatalog;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.TreeMap;

/**
 * Build step (exec-maven-plugin, process-classes): writes {@code META-INF/rule-fingerprints.properties}
 * with the SHA-256 of each rule's source files, keyed by {@link RuleCatalog} id (constitution P-2.5).
 * Line endings are normalized so the hash is the same on every OS.
 */
public final class RuleFingerprintWriter {

    private RuleFingerprintWriter() {}

    public static void main(String[] args) throws IOException {
        Path srcRoot = Path.of(args[0]);
        Path out = Path.of(args[1]);
        TreeMap<String, String> lines = new TreeMap<>();
        for (RuleCatalog rule : RuleCatalog.values()) {
            lines.put(rule.name(), sourceHash(srcRoot, rule));
        }
        Files.createDirectories(out.getParent());
        StringBuilder sb = new StringBuilder("# Generated by RuleFingerprintWriter. Do not edit.\n");
        lines.forEach((k, v) -> sb.append(k).append('=').append(v).append('\n'));
        try (OutputStream os = Files.newOutputStream(out)) {
            os.write(sb.toString().getBytes(java.nio.charset.StandardCharsets.UTF_8));
        }
    }

    static String sourceHash(Path srcRoot, RuleCatalog rule) throws IOException {
        MessageDigest sha = sha256();
        for (String cls : rule.sources().stream().sorted().toList()) {
            Path file = srcRoot.resolve(cls.replace('.', '/') + ".java");
            String text = Files.readString(file).replace("\r\n", "\n");
            sha.update(cls.getBytes(java.nio.charset.StandardCharsets.UTF_8));
            sha.update((byte) 0);
            sha.update(text.getBytes(java.nio.charset.StandardCharsets.UTF_8));
            sha.update((byte) 0);
        }
        return HexFormat.of().formatHex(sha.digest());
    }

    private static MessageDigest sha256() {
        try {
            return MessageDigest.getInstance("SHA-256");
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
