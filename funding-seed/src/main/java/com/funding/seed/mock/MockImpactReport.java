package com.funding.seed.mock;

import java.util.List;
import java.util.Map;
import java.util.Objects;

/**
 * {@code target/seed-report/mock-impact.md} (P-5.4): what a regeneration changed, per API: stubs
 * added or removed, stubs whose body changed, and stubs whose expected outcome changed.
 */
public final class MockImpactReport {
    private MockImpactReport() {}

    public static String render(Map<String, MocksLock.Entry> was, Map<String, MocksLock.Entry> now, List<String> changedRules) {
        StringBuilder sb = new StringBuilder("# Mock impact report\n\n");
        sb.append("Generated by `make seed-regenerate`. Compares the new stubs with the committed `test/data/mocks.lock`.\n\n");
        sb.append("## Changed rules\n\n");
        if (changedRules.isEmpty()) {
            sb.append("None.\n\n");
        } else {
            changedRules.forEach(r -> sb.append("- ").append(r).append('\n'));
            sb.append('\n');
        }
        section(sb, "Expected-outcome changes (need review, P-5.5)", now.values().stream()
                .filter(e -> was.containsKey(e.id()) && !Objects.equals(was.get(e.id()).expect(), e.expect()))
                .map(e -> "`" + e.id() + "`: " + was.get(e.id()).expect() + " -> " + e.expect()).toList());
        section(sb, "Response body changes", now.values().stream()
                .filter(e -> was.containsKey(e.id()) && !Objects.equals(was.get(e.id()).response(), e.response()))
                .map(e -> "`" + e.id() + "`").toList());
        section(sb, "Added stubs", now.keySet().stream().filter(id -> !was.containsKey(id)).map(id -> "`" + id + "`").toList());
        section(sb, "Removed stubs", was.keySet().stream().filter(id -> !now.containsKey(id)).map(id -> "`" + id + "`").toList());
        sb.append("Total stubs: ").append(now.size()).append('\n');
        return sb.toString();
    }

    private static void section(StringBuilder sb, String title, List<String> lines) {
        sb.append("## ").append(title).append(" (").append(lines.size()).append(")\n\n");
        if (lines.isEmpty()) {
            sb.append("None.\n\n");
            return;
        }
        lines.forEach(l -> sb.append("- ").append(l).append('\n'));
        sb.append('\n');
    }
}
