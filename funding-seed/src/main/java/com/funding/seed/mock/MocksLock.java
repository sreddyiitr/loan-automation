package com.funding.seed.mock;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.dataformat.yaml.YAMLFactory;
import com.funding.domain.ExternalApi;
import com.funding.domain.RuleCatalog;
import com.funding.domain.RulesConfig;
import com.funding.seed.RuleFingerprints;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Collectors;

/**
 * {@code test/data/mocks.lock} (P-5.5): per stub its band, request key, response hash, expected
 * outcome, and the fingerprint of every rule that consumes its API. Rendered with env {@code {env}}
 * so the file is the same on every machine.
 */
public final class MocksLock {

    public record Entry(String id, String band, String requestKey, String response, String expect, String rules) {}

    private MocksLock() {}

    public static Map<String, Entry> entries(List<MockStub> stubs, RulesConfig config, RuleFingerprints fp) {
        Map<String, Entry> m = new TreeMap<>();
        for (MockStub s : stubs) {
            m.put(s.id(), new Entry(s.id(), s.band(), s.requestKey(), responseHash(s), s.expected(), rules(s.api(), config, fp)));
        }
        return m;
    }

    public static String render(Map<String, Entry> entries) {
        StringBuilder sb = new StringBuilder("# Generated by `make seed-regenerate` (constitution P-5.5). Do not edit by hand.\nstubs:\n");
        entries.values().forEach(e -> sb.append("  \"").append(e.id()).append("\":\n")
                .append("    band: ").append(e.band()).append('\n')
                .append("    requestKey: \"").append(e.requestKey().replace("\\", "\\\\").replace("\"", "\\\"")).append("\"\n")
                .append("    response: ").append(e.response()).append('\n')
                .append("    expect: ").append(e.expect()).append('\n')
                .append("    rules: \"").append(e.rules()).append("\"\n"));
        return sb.toString();
    }

    public static Map<String, Entry> read(Path file) {
        if (!Files.exists(file)) {
            return Map.of();
        }
        try {
            JsonNode root = new ObjectMapper(new YAMLFactory()).readTree(file.toFile());
            Map<String, Entry> m = new TreeMap<>();
            root.path("stubs").fields().forEachRemaining(e -> m.put(e.getKey(), new Entry(e.getKey(),
                    e.getValue().path("band").asText(), e.getValue().path("requestKey").asText(),
                    e.getValue().path("response").asText(), e.getValue().path("expect").asText(),
                    e.getValue().path("rules").asText())));
            return m;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Stale-lock messages; empty when the committed lock matches. */
    public static List<String> diff(Path file, Map<String, Entry> now) {
        if (!Files.exists(file)) {
            return List.of("mocks.lock is missing: run `make seed-regenerate`");
        }
        Map<String, Entry> was = read(file);
        List<String> out = new ArrayList<>();
        int added = 0, removed = 0, changed = 0;
        for (String id : now.keySet()) {
            if (!was.containsKey(id)) added++;
            else if (!was.get(id).equals(now.get(id))) changed++;
        }
        for (String id : was.keySet()) {
            if (!now.containsKey(id)) removed++;
        }
        if (added + removed + changed > 0) {
            out.add("mocks.lock is stale (" + added + " added, " + removed + " removed, " + changed
                    + " changed stubs): run `make seed-regenerate` and inspect target/seed-report/mock-impact.md");
        }
        return out;
    }

    static String rules(ExternalApi api, RulesConfig config, RuleFingerprints fp) {
        String s = Arrays.stream(RuleCatalog.values()).filter(r -> r.apis().contains(api))
                .map(r -> r.name() + "@" + fp.fingerprint(r, config).substring(0, 12))
                .collect(Collectors.joining(","));
        return s.isEmpty() ? "none" : s;
    }

    static String responseHash(MockStub s) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("interactions", s.interactions());
        try {
            byte[] json = new ObjectMapper().writeValueAsBytes(m);
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(json)).substring(0, 16);
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }

    static byte[] utf8(String s) {
        return s.getBytes(StandardCharsets.UTF_8);
    }
}
