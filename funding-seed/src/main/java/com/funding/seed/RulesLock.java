package com.funding.seed;

import com.fasterxml.jackson.databind.JsonNode;
import com.funding.domain.RuleCatalog;
import com.funding.domain.RulesConfig;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * {@code test/data/rules.lock}: per rule, its fingerprint, the inputs to it, and the scenarios last
 * verified against it (with their intent hashes). Written only by {@code make seed-regenerate}.
 */
public final class RulesLock {

    private RulesLock() {}

    public static String render(List<ScenarioIntent> scenarios, String baselineHash, RulesConfig config,
                                RuleFingerprints fp) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by `make seed-regenerate` (constitution P-2.5). Do not edit by hand.\n");
        sb.append("baseline: ").append(baselineHash).append('\n');
        sb.append("rules:\n");
        for (RuleCatalog rule : RuleCatalog.values()) {
            sb.append("  ").append(rule.name()).append(":\n");
            sb.append("    fingerprint: ").append(fp.fingerprint(rule, config)).append('\n');
            sb.append("    source: ").append(fp.sourceHash(rule)).append('\n');
            sb.append("    config:\n");
            fp.config(rule, config).forEach((k, v) ->
                    sb.append("      ").append(k).append(": \"").append(v).append("\"\n"));
            sb.append("    scenarios:\n");
            scenarios.stream().filter(s -> s.rules().contains(rule.name()))
                    .forEach(s -> sb.append("      ").append(s.id()).append(": ").append(s.intentHash()).append('\n'));
        }
        return sb.toString();
    }

    /** Lines that differ between the committed lock and the current state, phrased for the build log. */
    public static List<String> diff(Path lockFile, String expected) {
        if (!Files.exists(lockFile)) {
            return List.of(lockFile.getFileName() + " is missing: run `make seed-regenerate`");
        }
        String actual;
        try {
            actual = Files.readString(lockFile).replace("\r\n", "\n");
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        if (actual.equals(expected)) {
            return List.of();
        }
        Map<String, JsonNode> was = rules(actual);
        Map<String, JsonNode> now = rules(expected);
        List<String> out = new java.util.ArrayList<>();
        for (String rule : new java.util.TreeSet<>(now.keySet())) {
            JsonNode w = was.get(rule);
            JsonNode n = now.get(rule);
            if (w == null) {
                out.add(rule + ": not in rules.lock (new rule)");
            } else if (!w.path("fingerprint").equals(n.path("fingerprint"))) {
                out.add(rule + ": rule source or config changed (fingerprint " + abbrev(w.path("fingerprint").asText())
                        + " -> " + abbrev(n.path("fingerprint").asText()) + ")");
            } else if (!w.path("scenarios").equals(n.path("scenarios"))) {
                out.add(rule + ": scenario intents changed since last verified");
            }
        }
        was.keySet().stream().filter(r -> !now.containsKey(r)).forEach(r -> out.add(r + ": in rules.lock but no longer in RuleCatalog"));
        if (out.isEmpty()) {
            out.add("rules.lock differs (baseline or formatting)");
        }
        return out.stream().map(s -> s + ". Run `make seed-regenerate` after updating the scenario intent.").toList();
    }

    private static Map<String, JsonNode> rules(String yaml) {
        try {
            JsonNode root = new com.fasterxml.jackson.databind.ObjectMapper(
                    new com.fasterxml.jackson.dataformat.yaml.YAMLFactory()).readTree(yaml);
            Map<String, JsonNode> m = new TreeMap<>();
            root.path("rules").fields().forEachRemaining(e -> m.put(e.getKey(), e.getValue()));
            return m;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static String abbrev(String s) {
        return s.length() > 12 ? s.substring(0, 12) : s;
    }
}
